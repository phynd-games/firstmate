  make_phynd_fixture "$ROOT" "$fixture"
  : > "$curl_log"
  : > "$nix_log"
  : > "$activate_log"

  cat > "$fakebin/curl" <<'SH'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "${PHYN_DEV_CURL_LOG:?}"
