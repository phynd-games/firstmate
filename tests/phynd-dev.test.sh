test_install_noop_update_and_safe_backup() {
  local case_dir fixture home xdg state npm_prefix nix_log rebuild_log system_profile out count
  case_dir="$TMP_ROOT/lifecycle"
  fixture="$case_dir/repo"
  home="$case_dir/home"
  xdg="$home/custom-xdg"
  state="$home/.local/state/phynd-dev"
  npm_prefix="$home/.local/share/phynd-dev/npm"
  nix_log="$case_dir/nix.log"
  rebuild_log="$case_dir/rebuild.log"
  mkdir -p "$home" "$xdg/fresh"
  make_phynd_fixture "$ROOT" "$fixture"
  make_fake_phynd_tools "$case_dir/fakebin"
  PHYN_TEST_FAKEBIN="$case_dir/fakebin"
  export PHYN_TEST_FAKEBIN
  export PHYN_DEV_BACKUP_SUFFIX=test
  : > "$nix_log"
  : > "$rebuild_log"
  printf '%s\n' '{"captain_private":true}' > "$xdg/fresh/config.json"

  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" "$nix_log" "$rebuild_log" \
    "$fixture/phynd-dev" install) || fail "initial phynd-dev install failed: $out"
  assert_contains "$out" "activation state recorded" "initial install should record activation"
  [ -L "$xdg/fresh/config.json" ] || fail "Fresh config should be linked after install"
  [ "$(readlink "$xdg/fresh/config.json")" = "$fixture/config/fresh/config.json" ] \
    || fail "Fresh link should target the repository source"
  [ "$(cat "$xdg/fresh/config.json.phynd-dev-backup-test")" = '{"captain_private":true}' ] \
    || fail "existing Fresh configuration should be preserved in a backup"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 1 ] || fail "initial install should activate exactly once"

  out=$(cd /tmp && HOME="$home" PHYN_DEV_HOME="$home" \
    PHYN_DEV_UNAME_S=Darwin PHYN_DEV_UNAME_M=arm64 \
    "$home/.local/bin/phynd-dev" status) \
    || fail "the Home Manager-installed phynd-dev command failed: $out"
  assert_contains "$out" "checkout: $fixture" \
    "the installed phynd-dev command should resolve its repository root"

  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" install) \
    || fail "second phynd-dev install failed: $out"
  assert_contains "$out" "already converged" "second install should report a no-op"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 1 ] || fail "second install should not reactivate nix-darwin"

  rm "$home/.config/zsh/.zshrc"
  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" install) \
    || fail "phynd-dev should repair missing Home Manager shell state: $out"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 2 ] || fail "missing Home Manager shell state should trigger activation"

  PHYN_TEST_MISSING_BREW_PACKAGE=herdr
  export PHYN_TEST_MISSING_BREW_PACKAGE
  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" install) \
    || fail "phynd-dev should repair missing Homebrew formula state: $out"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 3 ] || fail "missing Homebrew formula should trigger activation"
  unset PHYN_TEST_MISSING_BREW_PACKAGE

  system_profile="$case_dir/system-profile"
  mkdir -p "$system_profile"
  cp "$case_dir/fakebin/fresh" "$system_profile/fresh"
  PHYN_TEST_SYSTEM_PROFILE="$system_profile"
  export PHYN_TEST_SYSTEM_PROFILE
  rm "$case_dir/fakebin/fresh"
  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" install) \
    || fail "phynd-dev should repair a Home Manager package shadowed by system PATH: $out"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 4 ] || fail "a stale system package should not suppress Home Manager repair"
  cp "$system_profile/fresh" "$case_dir/fakebin/fresh"
  chmod +x "$case_dir/fakebin/fresh"

  mkdir -p "$case_dir/globalbin"
  cp "$case_dir/fakebin/starship" "$case_dir/globalbin/starship"
  chmod +x "$case_dir/globalbin/starship"
  rm "$case_dir/fakebin/starship"
  PHYN_TEST_GLOBALBIN="$case_dir/globalbin"
  export PHYN_TEST_GLOBALBIN
  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" install) \
    || fail "phynd-dev should repair missing Nix-managed packages: $out"
  assert_contains "$out" "applying pinned nix-darwin" \
    "a missing managed package should invalidate the activation no-op"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 5 ] || fail "missing managed package should trigger one reactivation"
  cat > "$case_dir/fakebin/starship" <<'SH'
#!/usr/bin/env bash
printf '%s\n' '❯'
SH
  chmod +x "$case_dir/fakebin/starship"

  printf '\n# later repo configuration revision\n' >> "$fixture/config/starship.toml"
  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" \
    "$nix_log" "$rebuild_log" "$fixture/phynd-dev" update) \
    || fail "phynd-dev update failed: $out"
  assert_contains "$out" "applying pinned nix-darwin" "changed configuration should reactivate"
  count=$(wc -l < "$rebuild_log" | tr -d ' ')
  [ "$count" -eq 6 ] || fail "updated configuration should activate once more"
  pass "phynd-dev install, converged no-op, update, and safe backup paths are idempotent"
}

test_activation_handles_determinate_custom_conf() {
  local case_dir fixture home xdg state npm_prefix nix_log rebuild_log conf backup out expected
  case_dir="$TMP_ROOT/nix-custom-conf"
  fixture="$case_dir/repo"
  home="$case_dir/home"
  xdg="$home/.config"
  state="$home/.local/state/phynd-dev"
  npm_prefix="$home/.local/share/phynd-dev/npm"
  nix_log="$case_dir/nix.log"
  rebuild_log="$case_dir/rebuild.log"
  conf="$case_dir/etc/nix/nix.custom.conf"
  backup="$conf.before-nix-darwin"
  mkdir -p "$home" "$case_dir/etc/nix"
  make_phynd_fixture "$ROOT" "$fixture"
  make_fake_phynd_tools "$case_dir/fakebin"
  PHYN_TEST_FAKEBIN="$case_dir/fakebin"
  PHYN_DEV_NIX_CUSTOM_CONF="$conf"
  export PHYN_TEST_FAKEBIN PHYN_DEV_NIX_CUSTOM_CONF
  : > "$nix_log"
  : > "$rebuild_log"
  {
    printf '%s\n' \
      '# Written by https://github.com/DeterminateSystems/nix-installer.' \
      '# The contents below are based on options specified at installation time.'
    printf '\n'
  } > "$conf"
  expected=$(printf '%s\n%s' \
    '# Written by https://github.com/DeterminateSystems/nix-installer.' \
    '# The contents below are based on options specified at installation time.')

  out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" "$nix_log" "$rebuild_log" \
    "$fixture/phynd-dev" install) || fail "installer-owned Nix config should be preserved: $out"
  [ ! -e "$conf" ] || fail "installer-owned Nix config should be moved before activation"
  [ "$(cat "$backup")" = "$expected" ] \
    || fail "installer-owned Nix config should be retained byte-for-byte"
  assert_contains "$out" "preserved the Determinate installer Nix config" \
    "activation should report the preserved installer config"

  printf '%s\n' 'experimental-features = nix-command flakes' > "$conf"
  printf '\n# force a second activation\n' >> "$fixture/config/starship.toml"
  if out=$(phynd_env "$home" "$xdg" "$state" "$npm_prefix" "$nix_log" "$rebuild_log" \
    "$fixture/phynd-dev" install 2>&1); then
    fail "activation should reject an unrecognized Nix config"
  fi
  [ -f "$conf" ] || fail "an unrecognized Nix config should not be moved"
  assert_contains "$out" "unmanaged Nix config" \
    "activation should explain how to handle an unrecognized Nix config"
  pass "activation safely prepares the Determinate installer Nix config"

  unset PHYN_DEV_NIX_CUSTOM_CONF
}

